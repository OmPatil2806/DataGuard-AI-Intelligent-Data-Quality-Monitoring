"""Generate the rule documentation from configs/quality_rules.yml.

    python src/quality/rule_catalogue.py              # docs/rule_catalogue.md (definitions)
    python src/quality/rule_catalogue.py --results    # also docs/rule_results.md (latest run)

The catalogue is generated so it can never drift from the rules that actually run; a test
fails when the committed file is out of date. The results file is written from the
latest run_rules.py run in data/dataguard.duckdb.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

if __package__ in (None, ""):
    # Allow running this file directly: make src/ importable.
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from common import db  # noqa: E402
from common.config import REPO_ROOT, load_datasets_config  # noqa: E402
from quality.rules import ROW_CATEGORIES, Rule, load_rules  # noqa: E402

CATALOGUE = REPO_ROOT / "docs" / "rule_catalogue.md"
RESULTS = REPO_ROOT / "docs" / "rule_results.md"


def _fmt(value: object) -> str:
    return str(value)


def condition(rule: Rule) -> str:
    """What a row must satisfy to pass, in plain words."""
    p = rule.params
    check = rule.check
    if check == "not_null":
        cols = ", ".join(f"`{c}`" for c in p["columns"])
        if p.get("mode", "any") == "all":
            return f"not all of {cols} are empty"
        return f"{cols} are filled" if len(p["columns"]) > 1 else f"{cols} is filled"
    if check == "range":
        col = f"`{p['column']}`"
        parts = []
        if "min" in p:
            parts.append(f"{col} {'>' if p.get('exclusive_min') else '≥'} {_fmt(p['min'])}")
        if "max" in p:
            parts.append(f"{col} {'<' if p.get('exclusive_max') else '≤'} {_fmt(p['max'])}")
        return " and ".join(parts)
    if check == "allowed_values":
        return f"`{p['column']}` is one of {', '.join(map(_fmt, p['values']))}"
    if check == "forbidden_values":
        values = p["values"]
        if len(values) == 1:
            return f"`{p['column']}` ≠ {_fmt(values[0])}"
        return f"`{p['column']}` is not {', '.join(map(_fmt, values))}"
    if check == "compare":
        op = {"!=": "≠", ">=": "≥", "<=": "≤"}.get(p["op"], p["op"])
        return f"`{p['left']}` {op} `{p['right']}`"
    if check == "duration":
        parts = []
        if "min_seconds" in p:
            parts.append(f"at least {p['min_seconds']:,} s")
        if "max_seconds" in p:
            parts.append(f"at most {p['max_seconds']:,} s")
        return f"`{p['start']}` to `{p['end']}` lasts {' and '.join(parts)}"
    if check == "within_period":
        return f"`{p['column']}` is inside the file's month"
    if check == "foreign_key":
        return f"`{p['column']}` exists in lookup `{p['lookup']}.{p['lookup_column']}`"
    if check == "unique":
        return "first row with this " + ", ".join(f"`{c}`" for c in p["columns"])
    if check == "sum_equals":
        text = f"`{p['total']}` = sum of {', '.join(f'`{c}`' for c in p['parts'])}"
        for alternative in p.get("alternatives", []):
            text += f", or of {', '.join(f'`{c}`' for c in alternative)}"
        return text + f" (± {p.get('tolerance', 0.01)})"
    raise ValueError(f"unknown check '{check}'")


def _escape(text: str) -> str:
    return text.replace("|", "\\|")


def render_catalogue(rules: list[Rule], dataset_name: str) -> str:
    enabled = [r for r in rules if r.enabled]
    quarantine = sum(r.action == "quarantine" for r in enabled)
    lines = [
        f"# Rule catalogue: {dataset_name}",
        "",
        "<!-- Generated by `python src/quality/rule_catalogue.py` from "
        "configs/quality_rules.yml. Do not edit by hand. -->",
        "",
        f"{len(rules)} rules: {quarantine} quarantine and {len(enabled) - quarantine} warn "
        f"enabled, {len(rules) - len(enabled)} pending. Measured hit rates are in "
        "[rule_results.md](rule_results.md), written by "
        "`python src/quality/rule_catalogue.py --results`.",
        "",
        "- **quarantine**: the row is moved to Quarantine with its reasons (Phase 4).",
        "- **warn**: the row stays in Silver, flagged with its reasons.",
        "- A rule only judges values that are present: empty values pass every rule except the",
        "  completeness rules, so a missing value is reported once.",
        "- Rules run on the standard schema (configs/datasets.yml), after standardization.",
        "",
    ]
    for category in ROW_CATEGORIES:
        in_category = [r for r in rules if r.category == category]
        if not in_category:
            continue
        lines += [
            f"## {category.capitalize()}",
            "",
            "| Rule | A row passes when | Action | Severity | Why |",
            "|---|---|---|---|---|",
        ]
        for r in in_category:
            action = r.action if r.enabled else f"{r.action} (**pending**, disabled)"
            why = r.description or ""
            if r.when:
                why += f" Applies only when `{r.when}`."
            lines.append(
                f"| `{r.id}` | {_escape(condition(r))} | {action} | {r.severity} | {_escape(why)} |"
            )
        lines.append("")

    pending = [r for r in rules if not r.enabled]
    if pending:
        lines += ["## Pending", ""]
        lines += [f"- `{r.id}`: {r.description}" for r in pending]
        lines.append("")
    return "\n".join(lines)


def render_results(con, dataset_name: str) -> str | None:
    """Markdown with the hit rates of the latest rule run, or None without a run."""
    row = con.execute(
        "SELECT max(run_id) FROM rule_run_summary WHERE dataset = ?", [dataset_name]
    ).fetchone()
    if not row or row[0] is None:
        return None
    run_id = row[0]
    started = con.execute(
        "SELECT started_at FROM pipeline_runs WHERE run_id = ?", [run_id]
    ).fetchone()[0]
    per_rule = con.execute(
        """
        SELECT rule_id, action, sum(rows_failed) AS failed,
               100.0 * sum(rows_failed) / sum(rows_checked) AS pct,
               100.0 * max(rows_failed / rows_checked) AS worst,
               count_if(rows_failed > 0) AS months, count(*) AS checked_months
        FROM rule_run_log WHERE run_id = ? AND dataset = ?
        GROUP BY ALL ORDER BY failed DESC, rule_id
        """,
        [run_id, dataset_name],
    ).fetchall()
    per_month = con.execute(
        """
        SELECT period, rows_checked, rows_quarantined, rows_warned
        FROM rule_run_summary WHERE run_id = ? AND dataset = ? ORDER BY period
        """,
        [run_id, dataset_name],
    ).fetchall()
    total = sum(m[1] for m in per_month)
    lines = [
        f"# Rule results: {dataset_name}",
        "",
        f"<!-- Generated by `python src/quality/rule_catalogue.py --results` from {run_id}. -->",
        "",
        f"Run `{run_id}` ({started:%Y-%m-%d %H:%M} UTC): {len(per_month)} month(s), "
        f"{total:,} rows.",
        "",
        "## Per rule",
        "",
        "| Rule | Action | Rows failed | % of all rows | Worst month % | Months affected |",
        "|---|---|---:|---:|---:|---:|",
    ]
    lines += [
        f"| `{r}` | {a} | {f:,} | {p:.4f} | {w:.4f} | {m} of {n} |"
        for r, a, f, p, w, m, n in per_rule
    ]
    lines += [
        "",
        "## Per month",
        "",
        "| Month | Rows | Quarantined | % | Warned only | % |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    lines += [
        f"| {p} | {n:,} | {q:,} | {100 * q / n:.3f} | {w:,} | {100 * w / n:.3f} |"
        for p, n, q, w in per_month
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the rule catalogue and results.")
    parser.add_argument("--dataset", default="yellow_taxi", help="dataset name in datasets.yml")
    parser.add_argument("--results", action="store_true", help="also write rule_results.md")
    parser.add_argument("--database", type=Path, help="DuckDB file (default: paths.duckdb)")
    parser.add_argument("--out", type=Path, default=CATALOGUE, help="catalogue file")
    parser.add_argument("--results-out", type=Path, default=RESULTS, help="results file")
    args = parser.parse_args(argv)

    dataset = load_datasets_config().dataset(args.dataset)
    rules = load_rules(dataset, include_disabled=True)
    args.out.write_text(render_catalogue(rules, dataset.name), encoding="utf-8")
    print(f"written {args.out}")
    if not args.results:
        return 0
    try:
        con = db.connect(args.database, read_only=True)
    except FileNotFoundError as exc:
        print(exc)
        return 1
    with con:
        text = render_results(con, dataset.name)
    if text is None:
        print("no rule run found: run python src/quality/run_rules.py first")
        return 1
    args.results_out.write_text(text, encoding="utf-8")
    print(f"written {args.results_out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
